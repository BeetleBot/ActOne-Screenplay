"""Generate named Rust parity tests after the opt-in Vitest oracle capture."""
import json
import pathlib
import re

root = pathlib.Path(__file__).resolve().parents[2]
lines = ["// Generated by tests/file-core/generate-rust-tests.py; do not edit by hand."]
counter = 0
for path in sorted((root / "src-tauri/tests/fixtures/file-core").glob("*.json")):
    groups = {}
    for index, case in enumerate(json.loads(path.read_text(encoding="utf-8"))):
        groups.setdefault(case["test"], []).append(index)
    for name, indices in groups.items():
        counter += 1
        slug = re.sub(r"[^a-z0-9]+", "_", name.lower()).strip("_")[:150]
        lines.extend(["#[test]", f"fn oracle_{counter:03}_{slug}() {{", f'    run_oracle("{path.name}", &{indices});', "}"])
(root / "src-tauri/src/actone/oracle_cases.rs").write_text("\n".join(lines)+"\n", encoding="utf-8")
print(f"Generated {counter} named Rust parity tests.")
